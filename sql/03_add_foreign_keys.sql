-- =====================================================================
-- 03_add_foreign_keys.sql
-- Add the relationships after the data is loaded, so the load order of the
-- tables does not matter. These documented relationships are many-to-one
-- (many fact rows point to one dimension row).
-- =====================================================================

ALTER TABLE SUPERSTORE.FACT_SALES ADD CONSTRAINT FK_FACT_CUSTOMER
    FOREIGN KEY (CUSTOMER_ID) REFERENCES SUPERSTORE.DIM_CUSTOMER (CUSTOMER_ID);

ALTER TABLE SUPERSTORE.FACT_SALES ADD CONSTRAINT FK_FACT_PRODUCT
    FOREIGN KEY (PRODUCT_KEY) REFERENCES SUPERSTORE.DIM_PRODUCT (PRODUCT_KEY);

ALTER TABLE SUPERSTORE.FACT_SALES ADD CONSTRAINT FK_FACT_GEOGRAPHY
    FOREIGN KEY (GEO_KEY) REFERENCES SUPERSTORE.DIM_GEOGRAPHY (GEO_KEY);

ALTER TABLE SUPERSTORE.FACT_SALES ADD CONSTRAINT FK_FACT_ORDER
    FOREIGN KEY (ORDER_ID) REFERENCES SUPERSTORE.DIM_ORDER (ORDER_ID);

ALTER TABLE SUPERSTORE.FACT_SALES ADD CONSTRAINT FK_FACT_DATE
    FOREIGN KEY (ORDER_DATE) REFERENCES SUPERSTORE.DIM_DATE (CAL_DATE);
